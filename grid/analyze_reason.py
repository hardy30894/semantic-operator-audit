"""Analyse the reasoning runs (grid/reason.py) with the grid's own analysis, and compare them with reasoning off.

For Sonnet, Haiku and Luna at medium effort, every identity is pooled over the same units as the grid
(grid/analyze.py's analyse_model, unchanged: permutation test, Holm within the model over H1 to H7 and over S2
to S5), reading the rgrid-* runs. Beside each, the same model's reasoning-off estimate from grid/results/grid.json,
and the difference in excess divergence (reasoning on minus off) with a 95% interval from the two estimates'
intervals, taken as independent (the runs are separate sessions on the same items, so the interval is
conservative). Also, per model, the share of calls that reasoned (grid/verify_reason.py's rule, over the runs in scope).

Run from the project root:  python3 grid/analyze_reason.py [--quick]
Writes grid/results/reason.json and grid/results/REASON.md. Makes no model calls.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "grid"))
import analyze as A  # noqa: E402

ON = {"sonnet-5.5-reasoning-medium": "sonnet-5.5", "haiku-5.5-reasoning-medium": "haiku-5.5",
      "gpt-5.6-luna-reasoning-medium": "gpt-5.6-luna"}
SHORT = {"sonnet-5.5-reasoning-medium": "Sonnet", "haiku-5.5-reasoning-medium": "Haiku",
         "gpt-5.6-luna-reasoning-medium": "Luna"}


def sources() -> dict:
    out = {}
    for pair in A.PAIRS:
        cell = {"logic and rewordings": f"rgrid-{pair}-logic", "COUNT": f"rgrid-{pair}-logic",
                "batching": f"rgrid-{pair}-batch"}
        if pair.endswith("-A"):
            cell["idempotence"] = f"rgrid-{pair}-idem"
        out[pair] = cell
    for m in A.MATCH:
        out[m] = {"symmetry": f"rgrid-{m}-sym", "placement": f"rgrid-{m}-place"}
    return out


def reasoned_share(model: str) -> str:
    """Successful calls of the runs in scope that reasoned (grid/verify_reason.py's rule), as "k of n (p%)"."""
    import gzip

    from verify_reason import thinking

    runs = sorted({run for cell in sources().values() for run in cell.values()})
    k = n = 0
    for run in runs:
        path = A.H / "runs" / run / f"{model}.jsonl.gz"
        with gzip.open(path, "rt", encoding="utf-8") as fh:
            for line in fh:
                rec = json.loads(line)
                if rec.get("error"):
                    continue
                n += 1
                k += thinking(rec) > 0
    return f"{k:,} of {n:,} ({100 * k / n:.0f}%)"


def half_width(row: dict) -> float | None:
    ci = row.get("delta_ci")
    if not ci or ci[0] is None or ci[1] is None:
        return None
    return (ci[1] - ci[0]) / 2


def contrast(on: dict, off: dict) -> dict:
    if on.get("status") != "ok" or off.get("status") != "ok":
        return {"status": "not measured"}
    d = on["delta"] - off["delta"]
    h_on, h_off = half_width(on), half_width(off)
    if h_on is None or h_off is None:
        return {"status": "ok", "difference": d}
    h = math.sqrt(h_on ** 2 + h_off ** 2)
    return {"status": "ok", "difference": d, "ci": [d - h, d + h], "excludes_zero": d - h > 0 or d + h < 0}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args(argv)
    n_perm, n_boot, n_bin = (500, 200, 2000) if args.quick else (10000, 10000, 100000)
    suffix = "-quick" if args.quick else ""
    off_all = {r["model"]: r for r in json.loads((A.OUT / f"grid{suffix}.json").read_text())}
    results = []
    for model, off_model in ON.items():
        print(f"analysing {model}", flush=True)
        res = A.analyse_model(model, sources(), n_perm, n_boot, n_bin)
        A._cache.clear()
        off = {r["hypothesis"]: r for r in off_all[off_model]["comparisons"]}
        for r in res["comparisons"]:
            r["off"] = {k: off[r["hypothesis"]].get(k) for k in
                        ("status", "delta", "sqrt_delta", "delta_ci", "p_holm", "broken", "n_items")}
            r["on_minus_off"] = contrast(r, off[r["hypothesis"]])
        res["reasoned"] = reasoned_share(model)
        res["reasoning_off_model"] = off_model
        results.append(res)
    out = A.OUT
    (out / f"reason{suffix}.json").write_text(json.dumps(results, indent=1, default=str) + "\n", encoding="utf-8")
    lines = ["# Reasoning on (medium) against reasoning off", "",
             "√Δ̄ with reasoning on / off, pooled over the grid's units; bold: broken (Holm p < 0.05 within the model "
             "and run). Δ on − off: difference in excess divergence with a conservative 95% interval; * the interval "
             "excludes zero. COUNT in rows per batch of ten. Generated by `grid/analyze_reason.py`.", "",
             "| Test | " + " | ".join(f"{SHORT[r['model']]} on / off | Δ on − off" for r in results) + " |",
             "|---|" + "---|---|" * len(results)]
    for hyp in list(A.PRIMARY_HYPOTHESES) + list(A.SECONDARY_HYPOTHESES):
        cells = []
        for res in results:
            r = next(x for x in res["comparisons"] if x["hypothesis"] == hyp)
            f = lambda x: (("**%.2f**" % x["sqrt_delta"]) if x.get("broken") else "%.2f" % x["sqrt_delta"]) \
                if x.get("status") == "ok" else "–"
            c = r["on_minus_off"]
            dtxt = (f"{c['difference']:+.3f}" + ("*" if c.get("excludes_zero") else "")) if c.get("status") == "ok" else "–"
            cells += [f"{f(r)} / {f(r['off'])}", dtxt]
        lines.append(f"| {hyp} {A.LABEL[hyp]} | " + " | ".join(cells) + " |")
    lines += ["", "Calls that reasoned: " + "; ".join(f"{SHORT[r['model']]} {r['reasoned']}" for r in results) + "."]
    (out / f"REASON{suffix}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
