"""Rewordings in the consistent grid: per model, every rewording and the logic-vs-wording contrasts, pooled over
the 11 conditions (extension.placebo.pool_placebo, unchanged), and the contrasts with the condition as the unit
(REML with an HKSJ interval, as scripts/addendum_h_pairs.py does). Each model's runs are the ones
grid/coverage.json names: the earlier rewording runs for Haiku, Luna and Flash-Lite, the grid's combined runs
for the others. Only the base and reword segments enter; the earlier runs' Unknown segment is not read.

Run from the project root:  python3 grid/analyze_rewording.py [--models ...] [--quick]
Writes grid/results/rewording.json and grid/results/REWORDING.md. Makes no model calls.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
H = ROOT / "harness"
sys.path.insert(0, str(H))
sys.path.insert(0, str(H / "scripts"))
sys.path.insert(0, str(ROOT / "grid"))
import addendum_h_pairs as ahp  # noqa: E402
import extension.placebo as _placebo  # noqa: E402
from extension.placebo import pool_placebo  # noqa: E402

_truths = _placebo._truths


def _truths_or_none(config):
    """The pooled rewording analysis also scores accuracy where a condition has truth, which needs the dataset's
    records. WDC Products and Abt-Buy are not redistributed: without their records those accuracy fields are left out,
    and every rewording and identity estimate is unchanged."""
    try:
        return _truths(config)
    except FileNotFoundError:
        return {}


_placebo._truths = _truths_or_none
from semaudit.stats import holm  # noqa: E402

import analyze as A  # noqa: E402
from analyze import MODELS, PAIRS, SHORT  # noqa: E402

CONTRASTS = ["C1", "C2", "H2_vs_tmpl", "H2_vs_order", "S3_vs_pqpara", "H3_vs_S3"]


def analyse(model: str, sources: dict, quick: bool) -> dict:
    dirs = [H / "runs" / sources[p]["logic and rewordings"] for p in PAIRS]
    n = (500, 200, 2000) if quick else (10000, 10000, 100000)
    cwd = os.getcwd()
    os.chdir(H)
    try:
        res = pool_placebo(dirs, n_perm=n[0], n_boot=n[1], n_perm_binary=n[2], backends=[model])
    finally:
        os.chdir(cwd)
    arm = res["backends"][model]
    pairs = {c: ahp.pool(ahp.per_pair(res, model, c)) for c in CONTRASTS}
    for fam in (["C1", "C2"], CONTRASTS[2:]):
        ps = [pairs[c].get("p_hksj", 1.0) for c in fam]
        for c, adj in zip(fam, holm(ps)):
            pairs[c]["p_holm"] = adj
            pairs[c]["exceeds"] = pairs[c].get("status") != "insufficient data" and adj < 0.05 and pairs[c]["mu"] > 0
    return {"model": model, "pooled": arm, "pair_level": pairs, "runs": [d.name for d in dirs]}


def render(results: list[dict]) -> str:
    out = ["# Rewordings in the consistent grid", "",
           "Pair-level contrasts (the condition as the unit; REML, HKSJ, Holm over C1 and C2): mean difference in Δ̄ "
           "between the logical rewrite and the paraphrase, p after Holm. C1: negation vs paraphrase; C2: fusion vs "
           "the paraphrase of the conjunction. Generated by `grid/analyze_rewording.py`.", "",
           "| Model | C1 mean | C1 p (Holm) | C2 mean | C2 p (Holm) | Conditions |", "|---|---|---|---|---|---|"]
    for r in results:
        c1, c2 = r["pair_level"]["C1"], r["pair_level"]["C2"]
        f = lambda c: (f"{c['mu']:.3f}", f"{c['p_holm']:.3f}" + (" ✓" if c.get("exceeds") else "")) \
            if c.get("status") != "insufficient data" else ("–", "–")
        out.append(f"| {SHORT[r['model']]} | {f(c1)[0]} | {f(c1)[1]} | {f(c2)[0]} | {f(c2)[1]} | {c1.get('k', 0)} |")
    n = sum(1 for r in results if r["pair_level"]["C1"].get("exceeds"))
    m = sum(1 for r in results if r["pair_level"]["C2"].get("exceeds"))
    out += ["", f"C1 exceeds for {n} of {len(results)} models; C2 for {m} of {len(results)}."]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", nargs="*", default=[m for m in MODELS if m != "deepseek-v3.2"])
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args(argv)
    sources = json.loads((ROOT / "grid" / "coverage.json").read_text(encoding="utf-8"))["sources"]
    results = []
    for m in args.models:
        print(f"rewordings: {m}", flush=True)
        results.append(analyse(m, sources[m], args.quick))
    outdir = A.OUT
    outdir.mkdir(exist_ok=True)
    suffix = "-quick" if args.quick else ""
    (outdir / f"rewording{suffix}.json").write_text(json.dumps(results, indent=1, default=str) + "\n", encoding="utf-8")
    (outdir / f"REWORDING{suffix}.md").write_text(render(results), encoding="utf-8")
    print(f"wrote grid/results/REWORDING{suffix}.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
